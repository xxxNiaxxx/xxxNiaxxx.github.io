/** Languages the guest pages are written in (for the language switch). */
export const GUEST_PAGE_LANGUAGES = ["el", "en", "de", "fr", "it", "es"] as const;

export function guestPageText(lang: string | null | undefined): { lang: GuestLanguage; t: GuestPageText } {
  const code = (GUEST_PAGE_LANGUAGES as readonly string[]).includes(lang ?? "") ? (lang as GuestLanguage) : "en";
  return { lang: code, t: T[code] ?? en };
}
